"""Independent verification library (written from scratch; does NOT import the R2 code)."""
import numpy as np, math, itertools
from fractions import Fraction

def kappa(n):
    return math.pi ** (n / 2) / math.gamma(n / 2 + 1)

def enum_bfs(A, bound, tol=1e-9):
    """ALL nonzero integer x (both signs) with x^T A x <= bound.  Level-by-level Fincke-Pohst
    on the upper Cholesky factor (A = R^T R).  Returns (X, values)."""
    n = A.shape[0]
    R = np.linalg.cholesky(A).T
    X = np.zeros((1, n), dtype=np.int64)
    P = np.zeros(1)
    for i in range(n - 1, -1, -1):
        s = X[:, i + 1:] @ R[i, i + 1:]
        d = R[i, i]
        c = -s / d
        rad = np.sqrt(np.maximum(bound - P, 0.0)) / d
        lo = np.ceil(c - rad - tol).astype(np.int64)
        hi = np.floor(c + rad + tol).astype(np.int64)
        cnt = np.maximum(hi - lo + 1, 0)
        tot = int(cnt.sum())
        idx = np.repeat(np.arange(len(cnt)), cnt)
        starts = np.cumsum(cnt) - cnt
        off = np.arange(tot) - np.repeat(starts, cnt)
        v = lo[idx] + off
        Xn = X[idx].copy()
        Xn[:, i] = v
        Pn = P[idx] + (d * v + s[idx]) ** 2
        keep = Pn <= bound + tol
        X, P = Xn[keep], Pn[keep]
    nz = np.any(X != 0, axis=1)
    X = X[nz]
    vals = np.einsum('ij,jk,ik->i', X, A, X)
    return X, vals

def box_bruteforce(A, bound, maxsize=4e7):
    """Rigorous brute force: x^T A x <= bound implies x_i^2 <= bound*(A^-1)_ii (Cauchy-Schwarz).
    Enumerate the whole box.  Returns (min value over nonzero x, number of nonzero x with value<=bound) or None."""
    n = A.shape[0]
    Ai = np.linalg.inv(A)
    Bx = np.floor(np.sqrt(bound * np.diag(Ai)) + 1e-9).astype(int)
    size = float(np.prod(2 * Bx + 1))
    if size > maxsize:
        return None
    k = 0
    sz = 1
    # split: first block of coords iterated in python, rest vectorized
    while k < n and np.prod(2 * Bx[k:] + 1) > 3e5:
        k += 1
    rest = [np.arange(-b, b + 1) for b in Bx[k:]]
    G = np.stack(np.meshgrid(*rest, indexing='ij'), -1).reshape(-1, n - k).astype(float) if k < n else np.zeros((1, 0))
    A22 = A[k:, k:]
    q22 = np.einsum('ij,jk,ik->i', G, A22, G)
    mn = np.inf
    cnt = 0
    for head in itertools.product(*[range(-b, b + 1) for b in Bx[:k]]):
        h = np.array(head, dtype=float)
        val = q22 + 2 * (G @ (A[k:, :k] @ h)) + h @ A[:k, :k] @ h
        if not any(head):
            # exclude zero vector
            zero = np.all(G == 0, axis=1)
            val = np.where(zero, np.inf, val)
        mn = min(mn, float(val.min()))
        cnt += int((val <= bound).sum())
    return mn, cnt, size

def int_det(M):
    """exact determinant of an integer matrix (Bareiss via Fractions)."""
    n = len(M)
    M = [[Fraction(int(x)) for x in row] for row in M]
    det = Fraction(1)
    for i in range(n):
        p = None
        for r in range(i, n):
            if M[r][i] != 0:
                p = r
                break
        if p is None:
            return 0
        if p != i:
            M[i], M[p] = M[p], M[i]
            det = -det
        det *= M[i][i]
        inv = 1 / M[i][i]
        for r in range(i + 1, n):
            f = M[r][i] * inv
            if f != 0:
                for c in range(i, n):
                    M[r][c] -= f * M[i][c]
    return int(det)

def find_denominator(A, qmax=2000, tol=1e-6):
    for q in range(1, qmax + 1):
        Z = q * A
        if np.abs(Z - np.rint(Z)).max() < tol:
            return q
    return 0

def lattice_index(S, n):
    """index in Z^n of the lattice generated by the rows of S (0 if rank < n): integer row reduction."""
    M = [list(map(int, r)) for r in S]
    rows = M
    piv = []
    det = 1
    for c in range(n):
        # gcd-reduce column c among remaining rows
        cand = [r for r in rows if r[c] != 0]
        others = [r for r in rows if r[c] == 0]
        if not cand:
            return 0
        while len(cand) > 1:
            cand.sort(key=lambda r: abs(r[c]))
            p = cand[0]
            new = [p]
            for r in cand[1:]:
                f = r[c] // p[c]
                r2 = [a - f * b for a, b in zip(r, p)]
                if r2[c] != 0:
                    new.append(r2)
                else:
                    others.append(r2)
            cand = new
        det *= abs(cand[0][c])
        rows = [r for r in others if any(r)]
    return det
