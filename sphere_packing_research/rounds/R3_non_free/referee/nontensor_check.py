# invariance: multiplication by -w : (x,y) -> ? w*(x + w y) = w x + w^2 y = w x - (1+w) y = -y + w (x - y) ; conj: w -> w^2 = -1-w : x + (-1-w) y = (x-y) - w y
MW = np.block([[np.zeros((k,k)), -np.eye(k)],[np.eye(k), -np.eye(k)]]).T   # acts on row (x,y) -> (-y, x-y)
def act_w(v): x, y = v[:k], v[k:]; return np.concatenate([-y, x - y])
def act_c(v): x, y = v[:k], v[k:]; return np.concatenate([x - y, -y])
print("  invariant under w, conj:", all(in_lattice(act_w(b), B) for b in B), all(in_lattice(act_c(b), B) for b in B))
def tau2_line_D12(a, b):
    # line through w0 = a + b w (primitive): slice {w0 (x) z}: coordinates (a z, b z); condition (a+b) z mod 3 in C
    if (a + b) % 3 == 0: idx = 1
    else: idx = 3**(k - 2)       # z mod 3 must lie in C (dim 2)
    N = a*a - a*b + b*b
    cU = (2*N)**(k/2) * idx * c1
    return cU**(2/k) / cL**(2/(2*k)), idx, N
for (a, b) in [(1,0),(0,1),(1,1),(1,-1),(2,1),(1,2),(2,-1),(3,1),(1,3),(3,2),(4,1)]:
    t2, idx, N = tau2_line_D12(a, b)
    print(f"  line {a}+{b}w (N={N}): slice index {idx}, tau^2 = {t2:.4f} (need >= 2; f*tau^2 = {t2/2:.4f})")
