import numpy as np, itertools, math
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import smith_normal_form
rng = np.random.default_rng(1)

def hnf_basis(gens):
    """integer row-lattice basis from generators (rows) via sympy (small sizes)"""
    M = Matrix(gens)
    # row-reduce over Z using LLL-free approach: use Hermite via column ops on transpose
    from sympy.polys.matrices import DomainMatrix
    from sympy.polys.matrices.normalforms import hermite_normal_form
    H = hermite_normal_form(DomainMatrix.from_Matrix(M.T)).to_Matrix().T
    rows = [list(H.row(i)) for i in range(H.rows) if any(H.row(i))]
    return np.array(rows, dtype=float)

def covol(B, G):   # B integer coords (rows) w.r.t. ambient basis with Gram G
    B = np.array(B, dtype=float)
    return math.sqrt(abs(np.linalg.det(B @ G @ B.T)))

